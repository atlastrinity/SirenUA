    /// Повертає список районів для вказаної області.
    public static func districts(for region: String) -> [String] {
        districtsByRegion[region] ?? []
    }

    /// Повертає батьківську область для вказаного району.
    public static func parentRegion(for district: String) -> String? {
        for (region, districts) in districtsByRegion {
            if districts.contains(district) {
                return region
            }
        }
        return nil
    }

    /// Плоский список усіх 136 районів.
    public static var allDistricts: [String] {
        districtsByRegion.values.flatMap { $0 }
    }
